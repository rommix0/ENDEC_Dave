//! A native Rust reimplementation of the Loquendo TTS 6 engine.
//!
//! The original is a six-stage pipeline with one uniform module ABI per stage —
//! `Top`, `Les`, `Fon`, `Cat`, `Sig`, `Acu`. The module layout here mirrors
//! that exactly, so a function found in Ghidra has an obvious home:
//!
//! | ARM | here | job |
//! |---|---|---|
//! | `TopRun` `0x6521c` | [`top`] | charset, find-replace tables |
//! | `LesRun` `0x58b10` | [`les`] | tokenise, expand numbers, lexicon |
//! | `FonRun` `0x48c10` | [`fon`] | grapheme-to-phoneme, prosody |
//! | `CatRun` `0x3c21c` | [`cat`] | unit selection |
//! | `SigRun` `0x5af60` | [`sig`] | decode and splice units |
//! | `AcuRun` `0x36690` | [`acu`] | output |
//!
//! # Addresses
//!
//! The doc comments in this crate quote **Ghidra addresses** for `LoqTTS6.so`,
//! because that is where they were read. Ghidra loads at `0x10000` and
//! vaddr == file offset, so:
//!
//! ```text
//! elf_vaddr = ghidra_addr - 0x10000     (also the loqrs module offset)
//! ```
//!
//! `loqmsx.so` addresses are quoted the other way — as module offsets, matching
//! `loqrs`'s `NATIVE_PATCHES`. Add `0x10000` for the listing.
//!
//! Code never relies on that distinction: [`Stage::run_addr`] and
//! [`Stage::ghidra_addr`] each say which they are.
//!
//! **Nothing in this crate runs guest code.** The ARM engine is the oracle, and
//! it lives in `loqng-oracle`, behind a dev-dependency. Building this crate
//! must never pull in the interpreter.
//!
//! Status: scaffolding. See `PLAN.md` for the phase order — the stage modules
//! are empty until their phase starts, and each one is gated on byte-identical
//! output against the oracle.

